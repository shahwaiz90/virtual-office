/**
 * OpenCode / Antigravity Provider Adapter
 *
 * Generates:
 * - AGENTS.md (Discovery Anchor & Team Orchestration Manual)
 * - .agents/rules/team-orchestration.md (Workspace always-on rule)
 * - .agents/runtime-manifest.json (Pre-compiled subagent payloads)
 * - .agents/agents.json (Synchronized for backward compatibility)
 */

const path = require('path');
const BaseAdapter = require('./baseAdapter');
const { rolePrompt, rosterTable, skillsList, orchestratorOf, reportsToOf, delegatesOf, toolsOf } = require('./rolePrompt');

class OpenCodeAdapter extends BaseAdapter {
  constructor() {
    super('opencode', 'OpenCode & Antigravity runtime adapter');
    this.targetFiles = [
      'AGENTS.md',
      path.join('.agents', 'rules', 'team-orchestration.md'),
      path.join('.agents', 'runtime-manifest.json'),
      path.join('.agents', 'agents.json'),
    ];
  }

  buildMermaidDiagram(agents, orchestrator) {
    const lines = ['flowchart TD'];
    for (const ag of agents) {
      lines.push(`  ${ag.id}["${ag.name}<br/><i>${ag.role}${ag.id === orchestrator.id ? ' (orchestrator)' : ''}</i>"]`);
    }
    for (const ag of agents) {
      for (const tgtId of delegatesOf(ag)) {
        if (agents.some((a) => a.id === tgtId)) lines.push(`  ${ag.id} -->|delegates to| ${tgtId}`);
      }
    }
    return lines.join('\n');
  }

  buildSystemPrompt(agent, registry) {
    // A hand-written body in the role's definition wins over the generated prompt
    if (agent.instructions && agent.instructions.trim().length > 50) return agent.instructions.trim();
    // Antigravity/OpenCode roles start their delegates themselves with invoke_subagent
    return rolePrompt(agent, registry, { dispatch: 'invoke_subagent' });
  }

  async generate(registry, projectRoot, options = {}) {
    const filesWritten = [];
    const warnings = [];

    const agents = registry.agents || [];
    if (agents.length === 0) {
      return { success: false, filesWritten: [], warnings: ['No agents in registry'] };
    }

    const orchestrator = orchestratorOf(registry);
    const projectName = registry.name || path.basename(projectRoot);
    const reg = { ...registry, agents, name: projectName };

    // 1. AGENTS.md (read by Codex, OpenCode and Antigravity on every turn, so it stays short)
    const agentsMdContent = [
      `<!-- generated by node bin/agents.js sync: edit .agents/definitions/*.md instead -->`,
      `# ${projectName}: agent team`,
      ``,
      `ALWAYS INVOKE \`${orchestrator.id}\` FIRST: send every software request to ${orchestrator.name}, the orchestrator. It registers the request and role cards on the Kanban board, then delegates each card by key. Don't implement a request directly as a single agent.`,
      ``,
      '```mermaid',
      this.buildMermaidDiagram(agents, orchestrator),
      '```',
      ``,
      `## Team`,
      rosterTable(reg),
      ``,
      `Role definitions: \`.agents/definitions/<id>.md\`. Compiled prompts: \`.agents/runtime-manifest.json\`. Board protocol: \`.agents/skills/kanban-handoff/SKILL.md\`.`,
      ``,
      `## Skills`,
      skillsList(reg),
      ``,
      `## Registering subagents (\`define_subagent\`)`,
      `Use each role's \`registrationPayload\` from \`.agents/runtime-manifest.json\`: \`enable_subagent_tools\` for roles that delegate, \`enable_write_tools\` for roles that edit files.`,
      ``,
    ].join('\n');

    filesWritten.push(this.writeFileSafely(path.join(projectRoot, 'AGENTS.md'), agentsMdContent, options));

    // 2. Generate .agents/rules/team-orchestration.md
    const ruleContent = `---
name: team-orchestration
description: Route software requests through the orchestrator and the Kanban board.
always_on: true
---

# Team Orchestration

1. Send every software request to \`${orchestrator.id}\` (${orchestrator.name}) first. It registers the request on the Kanban board and breaks it into role cards (\`task-decomposition\` skill).
2. Roles delegate only along their \`delegation_targets\` (\`.agents/definitions/\`), with a prompt that names the card and nothing else (\`kanban-handoff\` skill).
3. Each role observes its prohibited actions.
`;

    filesWritten.push(this.writeFileSafely(path.join(projectRoot, '.agents', 'rules', 'team-orchestration.md'), ruleContent, options));

    // 3. Generate pre-compiled runtime manifest
    const runtimeAgents = agents.map((ag) => {
      const isPrimary = ag.id === orchestrator.id || Boolean(ag.is_primary);
      const prompt = this.buildSystemPrompt(ag, reg);
      const tools = toolsOf(ag).length ? toolsOf(ag) : ['view_file'];
      const handoff = delegatesOf(ag);
      return {
        id: ag.id,
        name: ag.name,
        role: ag.role,
        persona: ag.persona || '',
        goal: ag.goal || '',
        badge: ag.badge || ag.id.slice(0, 3).toUpperCase(),
        avatar_url: ag.avatar_url || '/assets/developer.png',
        description: ag.description || ag.role,
        skills: (ag.skillIds || []).map((skId) => ({ id: skId, path: `.agents/skills/${skId}/SKILL.md` })),
        skillIds: ag.skillIds || [],
        tools,
        allowed_tools: tools,
        enable_subagent_tools: Boolean(ag.enable_subagent_tools),
        enable_write_tools: Boolean(ag.enable_write_tools),
        enable_mcp_tools: Boolean(ag.enable_mcp_tools),
        inputContract: ag.inputContract || '',
        outputContract: ag.outputContract || '',
        permissions: ag.permissions || [],
        prohibited_actions: ag.prohibited_actions || [],
        reportsTo: reportsToOf(ag, orchestrator),
        handoffTo: handoff,
        delegation_targets: handoff,
        isPrimary,
        isSubagent: !isPrimary,
        parentAgent: isPrimary ? null : reportsToOf(ag, orchestrator),
        system_prompt: prompt,
        registrationPayload: {
          name: ag.id,
          description: `${ag.name} (${ag.role}${isPrimary ? ' - Primary Orchestrator' : ' - Subagent'}) - ${ag.description || ag.role}`,
          system_prompt: prompt,
          enable_subagent_tools: Boolean(ag.enable_subagent_tools),
          enable_write_tools: Boolean(ag.enable_write_tools),
          enable_mcp_tools: Boolean(ag.enable_mcp_tools),
        },
      };
    });

    const runtimeManifest = {
      registeredAt: new Date().toISOString(),
      projectRoot,
      orchestratorAgentId: orchestrator.id,
      orchestratorAgent: runtimeAgents.find((a) => a.id === orchestrator.id) || runtimeAgents[0],
      totalAgents: runtimeAgents.length,
      agents: runtimeAgents,
    };

    filesWritten.push(
      this.writeFileSafely(path.join(projectRoot, '.agents', 'runtime-manifest.json'), JSON.stringify(runtimeManifest, null, 2), options)
    );

    // 4. Synchronize .agents/agents.json for 100% backward compatibility
    const legacyAgentsJson = {
      $schema: 'https://raw.githubusercontent.com/google/virtual-office/main/agents-schema.json',
      version: '1.0.0',
      description: registry.description || `Virtual Office Multi-Agent Team for ${projectName}`,
      agents: agents.map((ag) => {
        const tools = toolsOf(ag).length ? toolsOf(ag) : ['view_file'];
        const handoff = delegatesOf(ag);
        return {
          id: ag.id,
          name: ag.name,
          role: ag.role,
          persona: ag.persona || '',
          goal: ag.goal || '',
          badge: ag.badge || ag.id.slice(0, 3).toUpperCase(),
          avatar_url: ag.avatar_url || '/assets/developer.png',
          description: ag.description || '',
          skills: ag.skillIds || [],
          tools,
          allowed_tools: tools,
          enable_subagent_tools: Boolean(ag.enable_subagent_tools),
          enable_write_tools: Boolean(ag.enable_write_tools),
          enable_mcp_tools: Boolean(ag.enable_mcp_tools),
          inputContract: ag.inputContract || '',
          outputContract: ag.outputContract || '',
          permissions: ag.permissions || [],
          prohibited_actions: ag.prohibited_actions || [],
          reportsTo: reportsToOf(ag, orchestrator),
          handoffTo: handoff,
          delegation_targets: handoff,
        };
      }),
    };

    // The server's startup registration passes keepAgentsJson: agents.json is user/Team Studio input there
    if (!options.keepAgentsJson) {
      filesWritten.push(
        this.writeFileSafely(path.join(projectRoot, '.agents', 'agents.json'), JSON.stringify(legacyAgentsJson, null, 2), options)
      );
    }

    return {
      success: true,
      filesWritten,
      warnings,
    };
  }
}

module.exports = OpenCodeAdapter;
