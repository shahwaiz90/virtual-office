/**
 * Claude Code Provider Adapter
 *
 * Generates:
 * - CLAUDE.md (Claude Code project instruction manual & orchestration guide)
 * - .claude/config.json (Project-level tool permissions & agent configurations)
 * - .claude/agents/<id>.md (one Claude Code subagent per role, so requests really route to the team)
 */

const fs = require('fs');
const path = require('path');
const BaseAdapter = require('./baseAdapter');
const { rolePrompt, DELEGATION_PROMPT, rosterTable, skillsList, orchestratorOf, reportsToOf, delegatesOf, toolsOf } = require('./rolePrompt');

// Marks subagent files this adapter owns, so stale ones can be removed without touching hand-written agents
const GENERATED_MARKER = '<!-- generated by Virtual Office: node bin/agents.js sync -->';

// Registry tool names (Antigravity/OpenCode vocabulary) -> Claude Code tools.
// invoke_subagent has no mapping: Claude Code subagents cannot start subagents (the main session dispatches).
const CLAUDE_TOOLS = {
  view_file: ['Read', 'Grep', 'Glob'],
  run_command: ['Bash'],
  git_diff: ['Bash'],
  write_to_file: ['Write'],
  replace_file_content: ['Edit'],
};

function claudeToolsFor(agent) {
  const tools = new Set(['Read', 'Grep', 'Glob', 'Bash']); // every role reads the board with curl
  for (const t of toolsOf(agent)) {
    for (const mapped of CLAUDE_TOOLS[t] || []) tools.add(mapped);
  }
  return Array.from(tools);
}

function subagentMarkdown(agent, registry, projectRoot) {
  const description = agent.description || agent.role;
  return [
    '---',
    `name: ${agent.id}`,
    `description: ${JSON.stringify(description)}`,
    `tools: ${claudeToolsFor(agent).join(', ')}`,
    '---',
    GENERATED_MARKER,
    '',
    rolePrompt(agent, { ...registry, name: registry.name || path.basename(projectRoot) }, { dispatch: 'handoff-lines' }),
  ].join('\n') + '\n';
}

class ClaudeAdapter extends BaseAdapter {
  constructor() {
    super('claude', 'Claude Code multi-agent adapter');
    this.targetFiles = [
      'CLAUDE.md',
      path.join('.claude', 'config.json'),
    ];
  }

  async generate(registry, projectRoot, options = {}) {
    const filesWritten = [];
    const warnings = [];

    const agents = registry.agents || [];
    if (agents.length === 0) {
      return { success: false, filesWritten: [], warnings: ['No agents in registry'] };
    }

    const orchestrator = orchestratorOf(registry);
    const projectName = registry.name || path.basename(projectRoot);

    // 1. Generate CLAUDE.md (loaded into every main-session turn, so it stays short)
    const claudeMdLines = [
      `<!-- generated by node bin/agents.js sync: edit .agents/definitions/*.md instead -->`,
      `# ${projectName}: agent team`,
      ``,
      `Route every software request to \`${orchestrator.id}\` (${orchestrator.name}), the orchestrator. Don't implement it directly in the main session.`,
      ``,
      `## Team`,
      rosterTable({ ...registry, agents }),
      ``,
      `Each role is a Claude Code subagent in \`.claude/agents/\`.`,
      ``,
      `## Dispatching (this session)`,
      `Subagents cannot start subagents, so this session dispatches:`,
      `1. Send the request to \`${orchestrator.id}\` with the Agent tool. It registers the cards and replies with \`HANDOFF <KEY> -> <agentId>\` lines.`,
      `2. For each HANDOFF line (respecting \`dependsOn\` on the cards), start that subagent with only: \`${DELEGATION_PROMPT}\``,
      `3. Repeat for the HANDOFF lines they return until the requirement card is done.`,
      ``,
      `Never paste instructions into a delegation prompt: everything is on the card (see the kanban-handoff skill).`,
      ``,
      `## Skills`,
      skillsList({ ...registry, agents }),
      ``,
      `## Commands`,
      `- \`npm run dev\` (UI), \`npm start\` (server on :3000), \`npm test\``,
      `- \`node bin/agents.js validate | sync | doctor | skills\`: edit \`.agents/definitions/*.md\`, then \`sync\` regenerates this file, \`.claude/agents/\`, AGENTS.md, GEMINI.md and \`.codex/\`.`,
      ``,
    ];

    const claudeMdContent = claudeMdLines.join('\n');
    filesWritten.push(this.writeFileSafely(path.join(projectRoot, 'CLAUDE.md'), claudeMdContent, options));

    // 2. Generate .claude/config.json
    const configData = {
      $schema: 'https://json.schemastore.org/claude-code-config.json',
      project: projectName,
      version: registry.version || '2.0.0',
      orchestrator: orchestrator.id,
      team: {
        agents: agents.map((ag) => {
          return {
            id: ag.id,
            name: ag.name,
            role: ag.role,
            primary: ag.id === orchestrator.id,
            tools: claudeToolsFor(ag),
            reportsTo: reportsToOf(ag, orchestrator),
            delegationTargets: delegatesOf(ag),
            skills: ag.skillIds || [],
            inputContract: ag.inputContract || '',
            outputContract: ag.outputContract || '',
            permissions: ag.permissions || [],
            prohibitedActions: ag.prohibited_actions || [],
          };
        }),
      },
      preferences: {
        strictOrchestratorRouting: true,
        enforceDelegationWhitelist: true,
        autoSyncRegistry: true,
      },
    };

    filesWritten.push(
      this.writeFileSafely(
        path.join(projectRoot, '.claude', 'config.json'),
        JSON.stringify(configData, null, 2),
        options
      )
    );

    // 3. Generate one Claude Code subagent per role, and drop generated ones for removed roles
    const agentsDir = path.join(projectRoot, '.claude', 'agents');
    const wanted = new Set(agents.map((ag) => `${ag.id}.md`));
    if (!options.dryRun && fs.existsSync(agentsDir)) {
      for (const file of fs.readdirSync(agentsDir)) {
        const full = path.join(agentsDir, file);
        if (!file.endsWith('.md') || wanted.has(file)) continue;
        try {
          if (fs.readFileSync(full, 'utf8').includes(GENERATED_MARKER)) fs.unlinkSync(full);
        } catch (e) {}
      }
    }
    for (const ag of agents) {
      const target = path.join(agentsDir, `${ag.id}.md`);
      if (fs.existsSync(target) && !fs.readFileSync(target, 'utf8').includes(GENERATED_MARKER)) {
        warnings.push(`Kept hand-written .claude/agents/${ag.id}.md (not generated by sync)`);
        continue;
      }
      filesWritten.push(this.writeFileSafely(target, subagentMarkdown(ag, registry, projectRoot), options));
    }

    return {
      success: true,
      filesWritten,
      warnings,
    };
  }
}

module.exports = ClaudeAdapter;

module.exports.subagentMarkdown = subagentMarkdown;
