/**
 * Claude Code Provider Adapter
 *
 * Generates:
 * - CLAUDE.md (Claude Code project instruction manual & orchestration guide)
 * - .claude/config.json (Project-level tool permissions & agent configurations)
 * - .claude/agents/<id>.md (one Claude Code subagent per role, so requests really route to the team)
 */

const fs = require('fs');
const path = require('path');
const BaseAdapter = require('./baseAdapter');

// Marks subagent files this adapter owns, so stale ones can be removed without touching hand-written agents
const GENERATED_MARKER = '<!-- generated by Virtual Office: node bin/agents.js sync -->';

// Registry tool names (Antigravity/OpenCode vocabulary) -> Claude Code tools.
// invoke_subagent has no mapping: Claude Code subagents cannot start subagents (the main session dispatches).
const CLAUDE_TOOLS = {
  view_file: ['Read', 'Grep', 'Glob'],
  run_command: ['Bash'],
  git_diff: ['Bash'],
  write_to_file: ['Write'],
  replace_file_content: ['Edit'],
};

function claudeToolsFor(agent) {
  const tools = new Set(['Read', 'Grep', 'Glob', 'Bash']); // every role reads the board with curl
  for (const t of agent.tools || agent.allowed_tools || []) {
    for (const mapped of CLAUDE_TOOLS[t] || []) tools.add(mapped);
  }
  return Array.from(tools);
}

// What each role posts to the Deliverables Hub (see kanban-handoff skill section 5)
function deliverableFor(agent) {
  const r = `${agent.role || ''} ${agent.id || ''}`.toLowerCase();
  if (r.includes('test') || r.includes('qa') || r.includes('quality')) {
    return '`test_report`: what you tested, environments, pass/fail per acceptance criterion, defects found.';
  }
  if (r.includes('scrum') || r.includes('product') || r.includes('pm')) {
    return '`prd`: the requirement breakdown: user need, scope, acceptance criteria, and the cards you created with their owners.';
  }
  if (r.includes('lead') || r.includes('architect')) {
    return '`architecture` when you hand work on: the technical contract (files, API shapes, data model, edge cases, how to verify). `code_review` when you review a card you delegated: your notes per acceptance criterion.';
  }
  return '`source_code`: the implementation summary: what changed and why, every changed file (also in `metadata.files`), how each acceptance criterion is met, how you tested.';
}

function subagentMarkdown(agent, registry, projectRoot) {
  const agents = registry.agents || [];
  const targets = agent.handoffTo || agent.delegation_targets || [];
  const skills = agent.skillIds || [];
  const nameOf = (id) => {
    const a = agents.find((x) => x.id === id);
    return a ? `\`${id}\` (${a.role})` : `\`${id}\``;
  };
  const lines = [
    '---',
    `name: ${agent.id}`,
    `description: ${JSON.stringify(`${agent.role} (${agent.id}). ${agent.description || ''}`.trim())}`,
    `tools: ${claudeToolsFor(agent).join(', ')}`,
    '---',
    GENERATED_MARKER,
    '',
    `You are **${agent.name}**, the ${agent.role} of the ${registry.name || path.basename(projectRoot)} agent team. Your agent id is \`${agent.id}\`; use it as \`agentId\` on every board call.`,
    '',
    '## The Kanban board is your only channel',
    'Read and follow `.agents/skills/kanban-handoff/SKILL.md` before anything else. In short:',
    '- Your instructions are on a card. Read it: `curl -s "http://localhost:3000/api/tasks/<KEY>?format=md"`. The prompt that started you only names the card.',
    '- Ask questions, record decisions and post progress on the card thread: `POST /api/tasks/<KEY>/thread`.',
    '- When you hand work on or finish, publish your deliverable first: `POST /api/deliverables` with `taskKey`, `agentId`, `type`, `title`, `summary` and `content` (skill section 5).',
    '- Finish by recording your result and moving the card: `POST /api/tasks/<KEY>/status`.',
    '- If you were started with a raw requirement instead of a card key, register it as a card first (see the skill), then work from the card.',
    '',
  ];
  if (agent.inputContract) lines.push('## What you read', agent.inputContract, '');
  if (agent.outputContract) lines.push('## What you deliver', agent.outputContract, '');
  lines.push(
    '## Your deliverable',
    `Post it to \`POST /api/deliverables\` with \`taskKey\` set to the card it is about, before you move that card. Type ${deliverableFor(agent)}`,
    ''
  );
  if (targets.length) {
    lines.push(
      '## Handing work on',
      `You may hand work only to: ${targets.map(nameOf).join(', ')}.`,
      'For each piece of work: register a card written for that role (brief, acceptance criteria, context, parentKey = your card), then delegate it by key.',
      'In Claude Code a subagent cannot start another subagent, so end your reply with the handoff list for the main session to dispatch, one per line:',
      '`HANDOFF <KEY> -> <agentId>`',
      'Do not repeat the brief in your reply; it is on the card.',
      ''
    );
  }
  lines.push(
    '## Handing work back',
    'When you move your card to `review`, end your reply with `HANDOFF <your KEY> -> <delegatedBy>` (the card\'s "Delegated by" agent) so the main session sends it back for review. Skip it only if you delegated the card to yourself.',
    'When you review a card you delegated: move it to `done`, or post what is missing and move it back to `in_progress` with `HANDOFF <its KEY> -> <its assignee>`.',
    ''
  );
  if (agent.prohibited_actions && agent.prohibited_actions.length) {
    lines.push('## Never', ...agent.prohibited_actions.map((a) => `- ${a}`), '');
  }
  if (skills.length) {
    lines.push('## Your skills', 'Read the ones relevant to your card before you start:');
    for (const sk of skills) lines.push(`- \`${sk}\`: .agents/skills/${sk}/SKILL.md`);
    lines.push('');
  }
  lines.push('## Your reply', 'Keep it to a pointer at the board, e.g. `WEB-312 -> review, result on the card` plus any HANDOFF lines. Everything else belongs on the card.');
  return lines.join('\n') + '\n';
}

class ClaudeAdapter extends BaseAdapter {
  constructor() {
    super('claude', 'Claude Code multi-agent adapter');
    this.targetFiles = [
      'CLAUDE.md',
      path.join('.claude', 'config.json'),
    ];
  }

  async generate(registry, projectRoot, options = {}) {
    const filesWritten = [];
    const warnings = [];

    const agents = registry.agents || [];
    if (agents.length === 0) {
      return { success: false, filesWritten: [], warnings: ['No agents in registry'] };
    }

    const orchestratorId = registry.orchestrator || agents[0].id;
    const orchestrator = agents.find((a) => a.id === orchestratorId) || agents[0];
    const projectName = registry.name || path.basename(projectRoot);

    // 1. Generate CLAUDE.md
    const claudeMdLines = [
      `# Claude Code Guidelines & Multi-Agent Team: ${projectName}`,
      ``,
      `> [!IMPORTANT]`,
      `> ### 🎯 PRIMARY ORCHESTRATOR ROUTING: \`${orchestrator.id}\``,
      `> **Always route incoming software engineering requests to \`${orchestrator.id}\` (${orchestrator.name}) first.**`,
      `> Do not perform monolithic implementation directly. The primary orchestrator deconstructs requests into structured sprint tasks, delegating to specialized team agents.`,
      ``,
      `---`,
      ``,
      `## 👥 Active Multi-Agent Team Roster`,
      ``,
      `| Agent ID | Role | Hierarchy | Allowed Tools | Delegation Targets |`,
      `| :--- | :--- | :--- | :--- | :--- |`,
    ];

    agents.forEach((ag) => {
      const isOrch = ag.id === orchestrator.id;
      const hierarchy = isOrch ? '**👑 Primary Orchestrator**' : '*Subagent Specialist*';
      const tools = (ag.tools || ag.allowed_tools || []).join(', ');
      const targets = (ag.handoffTo || ag.delegation_targets || []).join(', ') || '*None*';
      claudeMdLines.push(`| **\`${ag.id}\`** | ${ag.role} | ${hierarchy} | \`${tools}\` | \`${targets}\` |`);
    });

    claudeMdLines.push(``);
    claudeMdLines.push(`---`);
    claudeMdLines.push(``);
    claudeMdLines.push(`## 🔁 How Handoffs Work (Kanban Board = Agent Channel)`);
    claudeMdLines.push(``);
    claudeMdLines.push(`Each role is a Claude Code subagent in \`.claude/agents/\`. Subagents cannot start other subagents, so this main session is the dispatcher:`);
    claudeMdLines.push(``);
    claudeMdLines.push(`1. Send the user's requirement to \`${orchestrator.id}\` with the Agent tool. It registers a requirement card, breaks it into role-specific task cards on the board, and replies with \`HANDOFF <KEY> -> <agentId>\` lines.`);
    claudeMdLines.push(`2. For each HANDOFF line (respecting \`dependsOn\` on the cards), start that subagent with only: \`Your task: <KEY>. Read it with curl -s "http://localhost:3000/api/tasks/<KEY>?format=md" and follow the kanban-handoff skill.\``);
    claudeMdLines.push(`3. Repeat for HANDOFF lines those subagents return, until the requirement card is done.`);
    claudeMdLines.push(``);
    claudeMdLines.push(`Never paste instructions into a delegation prompt: everything an agent needs is on its card, and every question, decision and result goes on the card's thread, so the board shows the whole conversation.`);
    claudeMdLines.push(``);
    claudeMdLines.push(`---`);
    claudeMdLines.push(``);
    claudeMdLines.push(`## 🛠️ Essential Project Commands`);
    claudeMdLines.push(``);
    claudeMdLines.push(`- **Start Development Server:** \`npm run dev\``);
    claudeMdLines.push(`- **Launch Virtual Office Engine:** \`npm run launch\` or \`node server/launcher.js\``);
    claudeMdLines.push(`- **Validate Canonical Agent Registry:** \`node bin/agents.js validate\``);
    claudeMdLines.push(`- **Synchronize Multi-Provider Outputs:** \`node bin/agents.js sync\``);
    claudeMdLines.push(`- **Run Environment Diagnostics:** \`node bin/agents.js doctor\``);
    claudeMdLines.push(`- **Audit Skills:** \`node bin/agents.js skills\``);
    claudeMdLines.push(``);
    claudeMdLines.push(`---`);
    claudeMdLines.push(``);
    claudeMdLines.push(`## 🔒 Guardrails & Prohibited Actions`);
    claudeMdLines.push(``);

    agents.forEach((ag) => {
      if (ag.prohibited_actions && ag.prohibited_actions.length > 0) {
        claudeMdLines.push(`### \`${ag.id}\` (${ag.name})`);
        ag.prohibited_actions.forEach((act) => {
          claudeMdLines.push(`- 🚫 **${act}**`);
        });
        claudeMdLines.push(``);
      }
    });

    claudeMdLines.push(`---`);
    claudeMdLines.push(``);
    claudeMdLines.push(`## 🧠 Domain Skills Reference`);
    claudeMdLines.push(``);
    agents.forEach((ag) => {
      const skills = ag.skillIds || [];
      if (skills.length > 0) {
        claudeMdLines.push(`- **\`${ag.id}\`**: ${skills.map((s) => `[\`${s}\`](file://${path.join(projectRoot, '.agents', 'skills', s, 'SKILL.md')})`).join(', ')}`);
      }
    });
    claudeMdLines.push(``);

    const claudeMdContent = claudeMdLines.join('\n');
    filesWritten.push(this.writeFileSafely(path.join(projectRoot, 'CLAUDE.md'), claudeMdContent, options));

    // 2. Generate .claude/config.json
    const configData = {
      $schema: 'https://json.schemastore.org/claude-code-config.json',
      project: projectName,
      version: registry.version || '2.0.0',
      orchestrator: orchestrator.id,
      team: {
        agents: agents.map((ag) => {
          const tools = ag.tools || ag.allowed_tools || [];
          const handoff = ag.handoffTo || ag.delegation_targets || [];
          return {
            id: ag.id,
            name: ag.name,
            role: ag.role,
            persona: ag.persona || '',
            goal: ag.goal || '',
            primary: ag.id === orchestrator.id,
            tools,
            allowedTools: tools,
            reportsTo: ag.reportsTo || (ag.id === orchestrator.id ? 'user' : orchestrator.id),
            handoffTo: handoff,
            delegationTargets: handoff,
            skills: ag.skillIds || [],
            inputContract: ag.inputContract || '',
            outputContract: ag.outputContract || '',
            permissions: ag.permissions || [],
            prohibitedActions: ag.prohibited_actions || [],
          };
        }),
      },
      preferences: {
        strictOrchestratorRouting: true,
        enforceDelegationWhitelist: true,
        autoSyncRegistry: true,
      },
    };

    filesWritten.push(
      this.writeFileSafely(
        path.join(projectRoot, '.claude', 'config.json'),
        JSON.stringify(configData, null, 2),
        options
      )
    );

    // 3. Generate one Claude Code subagent per role, and drop generated ones for removed roles
    const agentsDir = path.join(projectRoot, '.claude', 'agents');
    const wanted = new Set(agents.map((ag) => `${ag.id}.md`));
    if (!options.dryRun && fs.existsSync(agentsDir)) {
      for (const file of fs.readdirSync(agentsDir)) {
        const full = path.join(agentsDir, file);
        if (!file.endsWith('.md') || wanted.has(file)) continue;
        try {
          if (fs.readFileSync(full, 'utf8').includes(GENERATED_MARKER)) fs.unlinkSync(full);
        } catch (e) {}
      }
    }
    for (const ag of agents) {
      const target = path.join(agentsDir, `${ag.id}.md`);
      if (fs.existsSync(target) && !fs.readFileSync(target, 'utf8').includes(GENERATED_MARKER)) {
        warnings.push(`Kept hand-written .claude/agents/${ag.id}.md (not generated by sync)`);
        continue;
      }
      filesWritten.push(this.writeFileSafely(target, subagentMarkdown(ag, registry, projectRoot), options));
    }

    return {
      success: true,
      filesWritten,
      warnings,
    };
  }
}

module.exports = ClaudeAdapter;

module.exports.subagentMarkdown = subagentMarkdown;
