/**
 * Gemini CLI Provider Adapter
 *
 * Generates:
 * - GEMINI.md (Context guidelines, primary orchestrator routing, subagent invocation schemas, tool boundaries)
 */

const path = require('path');
const BaseAdapter = require('./baseAdapter');
const { rosterTable, skillsList, orchestratorOf } = require('./rolePrompt');

class GeminiAdapter extends BaseAdapter {
  constructor() {
    super('gemini', 'Gemini CLI context and agent adapter');
    this.targetFiles = ['GEMINI.md'];
  }

  async generate(registry, projectRoot, options = {}) {
    const filesWritten = [];
    const warnings = [];

    const agents = registry.agents || [];
    if (agents.length === 0) {
      return { success: false, filesWritten: [], warnings: ['No agents in registry'] };
    }

    const orchestrator = orchestratorOf(registry);
    const projectName = registry.name || path.basename(projectRoot);
    const reg = { ...registry, agents, name: projectName };

    // GEMINI.md is loaded into every Gemini CLI turn, so it stays short; the protocol lives in the skill
    const lines = [
      `<!-- generated by node bin/agents.js sync: edit .agents/definitions/*.md instead -->`,
      `# ${projectName}: agent team (Gemini CLI)`,
      ``,
      `Route every software request to \`${orchestrator.id}\` (${orchestrator.name}), the orchestrator. It registers the request and role cards on the Kanban board before any code changes.`,
      ``,
      `## Team`,
      rosterTable(reg),
      ``,
      `## Delegation`,
      `Hand work on only along "Hands work to". A delegation prompt carries only the card reference: \`Your task: <KEY>. Read it with curl -s "$(cat .agents/portal-url 2>/dev/null || echo http://localhost:3000)/api/tasks/<KEY>?format=md" and follow the kanban-handoff skill.\` Everything else (brief, criteria, context, thread, result) is on the card; see \`.agents/skills/kanban-handoff/SKILL.md\`.`,
      ``,
      `## Skills`,
      skillsList(reg),
      ``,
    ];

    const content = lines.join('\n');
    filesWritten.push(this.writeFileSafely(path.join(projectRoot, 'GEMINI.md'), content, options));

    return {
      success: true,
      filesWritten,
      warnings,
    };
  }
}

module.exports = GeminiAdapter;
