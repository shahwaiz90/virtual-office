/**
 * OpenAI Codex Provider Adapter
 *
 * Generates:
 * - .codex/system-prompts.md (Codex multi-agent prompt directives and tool specifications)
 * - .codex/instructions.md (Project workspace instructions for Codex CLI/IDE)
 */

const path = require('path');
const BaseAdapter = require('./baseAdapter');
const { rolePrompt, rosterTable, skillsList, orchestratorOf } = require('./rolePrompt');

class CodexAdapter extends BaseAdapter {
  constructor() {
    super('codex', 'OpenAI Codex system prompt and tool adapter');
    this.targetFiles = [
      path.join('.codex', 'system-prompts.md'),
      path.join('.codex', 'instructions.md'),
    ];
  }

  async generate(registry, projectRoot, options = {}) {
    const filesWritten = [];
    const warnings = [];

    const agents = registry.agents || [];
    if (agents.length === 0) {
      return { success: false, filesWritten: [], warnings: ['No agents in registry'] };
    }

    const orchestrator = orchestratorOf(registry);
    const projectName = registry.name || path.basename(projectRoot);
    const reg = { ...registry, agents, name: projectName };

    // 1. .codex/instructions.md: who the team is and how work flows (prompts live in system-prompts.md)
    const instructions = [
      `<!-- generated by node bin/agents.js sync: edit .agents/definitions/*.md instead -->`,
      `# ${projectName}: Codex workspace instructions`,
      ``,
      `Start every request as \`${orchestrator.id}\` (${orchestrator.name}), the orchestrator: register it on the Kanban board and break it into role cards before any code changes. Each role's prompt is in \`.codex/system-prompts.md\`; the board protocol is in \`.agents/skills/kanban-handoff/SKILL.md\`.`,
      ``,
      `## Team`,
      rosterTable(reg),
      ``,
      `## Skills`,
      skillsList(reg),
      ``,
    ];
    filesWritten.push(this.writeFileSafely(path.join(projectRoot, '.codex', 'instructions.md'), instructions.join('\n'), options));

    // 2. .codex/system-prompts.md: one prompt per role
    const promptLines = [`<!-- generated by node bin/agents.js sync: edit .agents/definitions/*.md instead -->`, `# ${projectName}: role prompts`, ``];
    for (const ag of agents) {
      const custom = ag.instructions && ag.instructions.trim().length > 50 ? ag.instructions.trim() : null;
      promptLines.push(`## Agent Prompt: \`${ag.id}\` (${ag.name})`, ``, custom || rolePrompt(ag, reg, { dispatch: 'handoff-lines' }), ``);
    }
    filesWritten.push(this.writeFileSafely(path.join(projectRoot, '.codex', 'system-prompts.md'), promptLines.join('\n'), options));

    return {
      success: true,
      filesWritten,
      warnings,
    };
  }
}

module.exports = CodexAdapter;
